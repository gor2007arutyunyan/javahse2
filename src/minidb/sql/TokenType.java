package minidb.sql;

/** Виды лексем SQL-подобного языка. */
public enum TokenType {
    /** Идентификатор или ключевое слово. */
    IDENT,
    /** Целое число. */
    INTEGER,
    /** Число с десятичной точкой. */
    DECIMAL,
    /** Строковая константа в одинарных кавычках. */
    STRING,
    /** Знак препинания или оператор. */
    SYMBOL,
    /** Конец ввода. */
    EOF
}
